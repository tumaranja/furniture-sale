#!/usr/bin/env python3
"""Builds the example: index.html = template.html with the example data from example/data.json.

template.html is the only copy of the page code; it ships with an empty data block so
anything a seller doesn't fill in stays empty. Run this after changing either file:
    python3 scripts/build-example.py
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
template = (root / "template.html").read_text()
data = (root / "example" / "data.json").read_text().strip()
json.loads(data)  # fail loudly on broken JSON

tag = '<script type="application/json" id="sale-data">'
start = template.index(tag) + len(tag)
end = template.index("</script>", start)
example = template[:start] + "\n" + data + "\n" + template[end:]
example = example.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by scripts/build-example.py from template.html + example/data.json. Don't edit by hand. -->", 1)
(root / "index.html").write_text(example)
print("wrote index.html")
